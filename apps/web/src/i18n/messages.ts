export const FALLBACK_LOCALE: Locale = "en";
export const SUPPORTED_LOCALES = ["en", "ru"] as const satisfies readonly Locale[];

const loadedMessages: Partial<Record<Locale, TranslationMap>> = {
  en: enMessages,
};

export function getLoadedMessages(locale: Locale): TranslationMap | undefined {
  return loadedMessages[locale];
}

export async function ensureLocaleMessages(locale: Locale): Promise<TranslationMap> {
  const loaded = loadedMessages[locale];
  if (loaded) {
    return loaded;
  }

  if (locale === "ru") {
    const { ruMessages } = await import("./messages-ru");
    loadedMessages.ru = ruMessages;
    return ruMessages;
  }

  return enMessages;
}
